#!/usr/bin/env node
/**
 * Writes src/generated/dashboard-template.ts from the tokens package's built
 * dashboard template.
 *
 * The template travels as a string constant rather than a file read at
 * runtime, for the same reason the dataset does: the plugin ships as one
 * bundled file, and esbuild can follow an import where it cannot follow a
 * path worked out at runtime. The generated module is not committed. It is
 * rebuilt by every build and every typecheck, and the tokens package builds
 * before this one, so it is never stale.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const require = createRequire(import.meta.url);

// Resolved through the package's own exports map, which is how the tool would
// find it if it read the file at runtime.
const source = require.resolve('@betteruseofai/tokens/dashboard.html');

if (!existsSync(source)) {
  console.error(`No dashboard template at ${source}. Run: pnpm --filter @betteruseofai/tokens build`);
  process.exit(1);
}

const html = readFileSync(source, 'utf8');
const outDir = join(root, 'src', 'generated');
mkdirSync(outDir, { recursive: true });

const body = `// Generated by scripts/embed-template.mjs from @betteruseofai/tokens. Do not edit.
/* eslint-disable */
export const DASHBOARD_TEMPLATE: string = ${JSON.stringify(html)};
`;

writeFileSync(join(outDir, 'dashboard-template.ts'), body, 'utf8');
console.log(`  ${Math.round(html.length / 1024)} kB  src/generated/dashboard-template.ts`);
